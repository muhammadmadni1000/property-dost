// ============================================================
// PROPERTY DOST - Database & Domain TypeScript Definitions
// Strictly mapped to Supabase PostgreSQL Schema
// ============================================================

export type PropertyType =
  | 'House'
  | 'Plot'
  | 'Flat'
  | 'Shop'
  | 'Office'
  | 'Agricultural Land'
  | 'Commercial Property';

export type PropertyPurpose = 'For Sale' | 'For Rent';

export type PropertyStatus = 'Available' | 'Sold' | 'Rented';

export type VisitStatus = 'Requested' | 'Confirmed' | 'Visited' | 'Cancelled';

export type InquiryStatus = 'New' | 'Contacted' | 'Resolved';

export interface Property {
  id: string; // Genuine PostgreSQL UUID generated by gen_random_uuid()
  title: string;
  property_type: PropertyType;
  purpose: PropertyPurpose;
  location: string;
  city: string;
  area: number;
  area_unit: string; // 'Marla' | 'Kanal' | 'Square Feet'
  price: number;
  bedrooms: number;
  bathrooms: number;
  description: string;
  features: string[];
  image_url: string;
  images: string[];
  status: PropertyStatus;
  dealer_name?: string;
  dealer_phone?: string;
  dealer_whatsapp?: string;
  created_at?: string;
  updated_at?: string;
}

export interface Customer {
  id: string; // Genuine PostgreSQL UUID
  name: string;
  phone: string;
  email?: string | null;
  created_at?: string;
}

export interface Visit {
  id: string; // Genuine PostgreSQL UUID
  property_id: string;
  customer_id: string;
  visit_date: string;
  visit_time: string;
  status: VisitStatus;
  message?: string | null;
  created_at?: string;
  updated_at?: string;
  // Joined relation objects
  property?: Property;
  customer?: Customer;
}

export interface Inquiry {
  id: string; // Genuine PostgreSQL UUID
  customer_id?: string | null;
  property_id?: string | null;
  message: string;
  status: InquiryStatus;
  created_at?: string;
  // Joined relation objects
  property?: Property;
  customer?: Customer;
}

export interface PropertyFilters {
  searchTerm?: string;
  propertyType?: string;
  purpose?: string;
  city?: string;
  location?: string;
  minPrice?: number;
  maxPrice?: number;
  bedrooms?: number | 'any';
  status?: PropertyStatus | 'all';
  sortBy?: 'newest' | 'price-asc' | 'price-desc' | 'area-asc' | 'area-desc';
}

export interface BookingFormData {
  propertyId: string;
  name: string;
  phone: string;
  email?: string;
  visitDate: string;
  visitTime: string;
  message?: string;
}

export interface InquiryFormData {
  name: string;
  phone: string;
  email?: string;
  propertyId?: string;
  message: string;
}

export interface DashboardStats {
  totalProperties: number;
  availableProperties: number;
  soldProperties: number;
  rentedProperties: number;
  todayVisits: number;
  pendingVisits: number;
  confirmedVisits: number;
  totalVisits: number;
  newInquiries: number;
}

export type ConnectionState =
  | 'checking'
  | 'connected'
  | 'error'
  | 'unconfigured';

export interface SupabaseHealthStatus {
  state: ConnectionState;
  message: string;
  urlConfigured: boolean;
  keyConfigured: boolean;
  verifiedAt?: Date;
  errorDetail?: string;
}
