import { supabase } from '../lib/supabase';
import type { Customer } from '../types/database';

export async function findOrCreateCustomer(
  name: string,
  phone: string,
  email?: string
): Promise<Customer> {
  const cleanPhone = phone.trim();
  const cleanName = name.trim();
  const cleanEmail = email?.trim() || null;

  // 1. Try finding existing customer by phone
  const { data: existing, error: searchError } = await supabase
    .from('customers')
    .select('*')
    .eq('phone', cleanPhone)
    .limit(1);

  if (searchError) {
    throw new Error(`Customer search failed: ${searchError.message}`);
  }

  if (existing && existing.length > 0) {
    // Optionally update email or name if missing
    const customer = existing[0] as Customer;
    if ((!customer.email && cleanEmail) || (cleanName && customer.name !== cleanName)) {
      await supabase
        .from('customers')
        .update({
          name: cleanName || customer.name,
          email: cleanEmail || customer.email,
        })
        .eq('id', customer.id);
    }
    return customer;
  }

  // 2. Insert new customer - ID generated by Supabase PostgreSQL
  const { data: created, error: insertError } = await supabase
    .from('customers')
    .insert([
      {
        name: cleanName,
        phone: cleanPhone,
        email: cleanEmail,
      },
    ])
    .select()
    .single();

  if (insertError) {
    throw new Error(`Unable to create customer profile: ${insertError.message}`);
  }

  return created as Customer;
}

export async function getCustomers(): Promise<Customer[]> {
  const { data, error } = await supabase
    .from('customers')
    .select('*')
    .order('created_at', { ascending: false });

  if (error) {
    throw new Error(`Unable to fetch customers: ${error.message}`);
  }

  return (data as Customer[]) || [];
}
