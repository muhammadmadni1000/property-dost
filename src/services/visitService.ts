import { supabase } from '../lib/supabase';
import type { BookingFormData, Visit, VisitStatus } from '../types/database';
import { getPropertyById } from './propertyService';
import { findOrCreateCustomer } from './customerService';

/**
 * Visit Service
 * Manages physical property tour bookings and appointments.
 * Strictly uses Supabase PostgreSQL without any fake success or localStorage fallback.
 */

export async function createVisitBooking(formData: BookingFormData): Promise<Visit> {
  // STEP 1: Validate form data
  if (!formData.name || !formData.name.trim()) {
    throw new Error('Customer full name is required');
  }

  if (!formData.phone || !formData.phone.trim()) {
    throw new Error('Customer mobile number is required');
  }

  if (!formData.visitDate) {
    throw new Error('Visit date is required');
  }

  const selectedDate = new Date(formData.visitDate);
  const today = new Date();
  today.setHours(0, 0, 0, 0);

  if (selectedDate < today) {
    throw new Error('Visit date cannot be in the past');
  }

  if (!formData.visitTime) {
    throw new Error('Visit time is required');
  }

  if (!formData.propertyId) {
    throw new Error('Property ID is required');
  }

  // STEP 2: Verify property exists in Supabase by exact ID
  const property = await getPropertyById(formData.propertyId);
  if (!property || !property.id) {
    throw new Error('Property not found in database');
  }

  // STEP 3: Pre-check requested property/date/time slot for quick feedback
  const { data: existingSlot, error: checkError } = await supabase
    .from('visits')
    .select('id, status')
    .eq('property_id', property.id)
    .eq('visit_date', formData.visitDate)
    .eq('visit_time', formData.visitTime)
    .neq('status', 'Cancelled')
    .maybeSingle();

  if (checkError) {
    throw new Error(`Unable to verify slot availability: ${checkError.message}`);
  }

  if (existingSlot) {
    throw new Error('This property visit slot is already booked. Please choose another time or date.');
  }

  // STEP 4: Create or match customer in Supabase
  const customer = await findOrCreateCustomer(
    formData.name,
    formData.phone,
    formData.email
  );

  // STEP 5: Create visit row in Supabase
  // Note: visits.id is generated by gen_random_uuid(). We do not pass an id.
  const { data: createdVisit, error: insertError } = await supabase
    .from('visits')
    .insert([
      {
        property_id: property.id,
        customer_id: customer.id,
        visit_date: formData.visitDate,
        visit_time: formData.visitTime,
        status: 'Requested',
        message: formData.message?.trim() || null,
      },
    ])
    .select(`
      *,
      property:properties(*),
      customer:customers(*)
    `)
    .single();

  // STEP 6: Handle duplicate violation or insertion error
  if (insertError) {
    // 23505 is PostgreSQL unique_violation code
    if (insertError.code === '23505' || insertError.message.toLowerCase().includes('unique')) {
      throw new Error('This property visit slot is already booked. Please choose another time or date.');
    }
    throw new Error(`Unable to submit visit request: ${insertError.message}`);
  }

  if (!createdVisit) {
    throw new Error('Unable to submit visit request: No confirmation received from database');
  }

  // STEP 7: Return genuine visit record with Supabase-generated UUID
  return createdVisit as Visit;
}

export async function getVisits(): Promise<Visit[]> {
  const { data, error } = await supabase
    .from('visits')
    .select(`
      *,
      property:properties(*),
      customer:customers(*)
    `)
    .order('created_at', { ascending: false });

  if (error) {
    throw new Error(`Unable to fetch visits: ${error.message}`);
  }

  return (data as Visit[]) || [];
}

export async function updateVisitStatus(
  id: string,
  status: VisitStatus
): Promise<Visit> {
  const { data, error } = await supabase
    .from('visits')
    .update({ status })
    .eq('id', id)
    .select(`
      *,
      property:properties(*),
      customer:customers(*)
    `)
    .single();

  if (error) {
    throw new Error(`Unable to update visit status: ${error.message}`);
  }

  return data as Visit;
}

export async function deleteVisit(id: string): Promise<void> {
  const { error } = await supabase
    .from('visits')
    .delete()
    .eq('id', id);

  if (error) {
    throw new Error(`Unable to delete visit: ${error.message}`);
  }
}
