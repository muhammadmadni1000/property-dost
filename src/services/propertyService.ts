import { supabase } from '../lib/supabase';
import type { Property, PropertyFilters } from '../types/database';

/**
 * Property Service
 * All queries execute against the real Supabase PostgreSQL 'properties' table.
 * Strictly NO local mock arrays, NO fallback dummy data.
 */

export async function getProperties(filters?: PropertyFilters): Promise<Property[]> {
  let query = supabase.from('properties').select('*');

  if (filters) {
    if (filters.status && filters.status !== 'all') {
      query = query.eq('status', filters.status);
    }

    if (filters.propertyType && filters.propertyType !== 'All') {
      query = query.eq('property_type', filters.propertyType);
    }

    if (filters.purpose && filters.purpose !== 'All') {
      query = query.eq('purpose', filters.purpose);
    }

    if (filters.city && filters.city !== 'All') {
      query = query.eq('city', filters.city);
    }

    if (filters.minPrice !== undefined && filters.minPrice > 0) {
      query = query.gte('price', filters.minPrice);
    }

    if (filters.maxPrice !== undefined && filters.maxPrice > 0) {
      query = query.lte('price', filters.maxPrice);
    }

    if (filters.bedrooms && filters.bedrooms !== 'any') {
      query = query.gte('bedrooms', Number(filters.bedrooms));
    }

    if (filters.searchTerm && filters.searchTerm.trim() !== '') {
      const term = filters.searchTerm.trim();
      // Search across title, location, or description
      query = query.or(`title.ilike.%${term}%,location.ilike.%${term}%,description.ilike.%${term}%`);
    }

    // Sorting
    switch (filters.sortBy) {
      case 'price-asc':
        query = query.order('price', { ascending: true });
        break;
      case 'price-desc':
        query = query.order('price', { ascending: false });
        break;
      case 'area-asc':
        query = query.order('area', { ascending: true });
        break;
      case 'area-desc':
        query = query.order('area', { ascending: false });
        break;
      case 'newest':
      default:
        query = query.order('created_at', { ascending: false });
        break;
    }
  } else {
    query = query.order('created_at', { ascending: false });
  }

  const { data, error } = await query;

  if (error) {
    throw new Error(`Unable to load properties: ${error.message}`);
  }

  return (data as Property[]) || [];
}

export async function getPropertyById(id: string): Promise<Property> {
  if (!id || typeof id !== 'string') {
    throw new Error('Property ID is required');
  }

  const { data, error } = await supabase
    .from('properties')
    .select('*')
    .eq('id', id)
    .single();

  if (error) {
    throw new Error(`Property not found: ${error.message}`);
  }

  if (!data) {
    throw new Error('Property not found');
  }

  return data as Property;
}

export async function createProperty(
  propertyData: Omit<Property, 'id' | 'created_at' | 'updated_at'>
): Promise<Property> {
  // CRITICAL: ID is generated by Supabase PostgreSQL gen_random_uuid().
  // Do NOT pass an id column.
  const { data, error } = await supabase
    .from('properties')
    .insert([propertyData])
    .select()
    .single();

  if (error) {
    throw new Error(`Unable to save property: ${error.message}`);
  }

  return data as Property;
}

export async function updateProperty(
  id: string,
  propertyData: Partial<Omit<Property, 'id' | 'created_at' | 'updated_at'>>
): Promise<Property> {
  const { data, error } = await supabase
    .from('properties')
    .update(propertyData)
    .eq('id', id)
    .select()
    .single();

  if (error) {
    throw new Error(`Unable to update property: ${error.message}`);
  }

  return data as Property;
}

export async function deleteProperty(id: string): Promise<void> {
  const { error } = await supabase
    .from('properties')
    .delete()
    .eq('id', id);

  if (error) {
    throw new Error(`Unable to delete property: ${error.message}`);
  }
}
